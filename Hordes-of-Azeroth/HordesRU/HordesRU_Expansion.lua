end

local function Translate(text)
    if type(text) ~= "string" or text == "" then return text end
    if Exact[text] then return Exact[text] end
    local form = TranslateShapeshift(text)
    if form then return form end
    local numberedStat = TranslateServerStats(text)
    if numberedStat then return numberedStat end
    local fromBase = CheckEnglishName(text)
    if fromBase then return fromBase end
    local result = Numbered(text) or ReplaceTemplates(text) or TranslateFragments(text)
    if result then return result end
    local prefix, body, suffix = Match(text, "^(%s*)(.-)(%s*)$")
    if body ~= text then
        local found = Exact[body] or CheckEnglishName(body) or Numbered(body) or ReplaceTemplates(body) or TranslateFragments(body)
        if found then return prefix..found..suffix end
    end
    -- Preserve WoW colour markup, translating just its content.
    local color, inner = Match(text, "^|c(%x%x%x%x%x%x%x%x)(.-)|r$")
    if color then
        local found = Exact[inner] or CheckEnglishName(inner) or Numbered(inner) or ReplaceTemplates(inner) or TranslateFragments(inner)
        if found then return "|c" .. color .. found .. "|r" end
    end
    return text
end

