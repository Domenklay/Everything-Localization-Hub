    work = string.gsub(work, "^([%d%.]+) seconds?$", "%1 сек.")
    work = string.gsub(work, "^(%d+)%% chance$", "Шанс: %1%%")
    -- Dynamic percentages may have fractional parts.
    work = string.gsub(work, "^([%d%.]+)%% chance$", "Шанс: %1%%")
    work = string.gsub(work, "^([%d%.]+)%% more health$", "На %1%% больше здоровья")
    work = string.gsub(work, "^([%d%.]+) k Armor$", "%1 тыс. к броне")
    -- A card title may have the generic card label on the same line.
    if string.find(work, "Darkmoon Card:", 1, true) then
        for english, russian in pairs(v19pairs) do
            if string.find(english, "^Darkmoon Card:") then
                work = string.gsub(work, "^" .. string.gsub(english, "([%%%+%-%^%$%(%)%[%]%*%?%.])", "%%%1") .. "$", russian)
            end
        end
    end
    if work ~= text then
        work = string.gsub(work, "(%d+)%.(%d+)", "%1,%2")
        return work
    end
    return nil
end


