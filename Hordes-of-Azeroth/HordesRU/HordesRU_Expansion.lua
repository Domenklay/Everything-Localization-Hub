-- v1.10: the spell tooltip is a nameless top-level frame. Unlike GameTooltip,
-- it is populated through VanillaBonkSpellTip methods before layout.
local spellTipHooked = false
local gameTipHooked = false
local function HookSpecialTooltips()
    local tip = VanillaBonkSpellTip
    if not spellTipHooked and type(tip) == "table" and type(tip.AddLine) == "function" then
        local oldLine = tip.AddLine
        tip.AddLine = function(self, content, r, g, b)
            return oldLine(self, enabled and Translate(content) or content, r, g, b)
        end
        if type(tip.Title) == "function" then
            local oldTitle = tip.Title
            tip.Title = function(self, content, color, tags)
                return oldTitle(self, enabled and Translate(content) or content, color, tags)
            end
        end
        if type(tip.AddSmallLine) == "function" then
            local oldSmall = tip.AddSmallLine
            tip.AddSmallLine = function(self, content, color)
                return oldSmall(self, enabled and Translate(content) or content, color)
            end
        end
        if type(tip.AddDoubleLine) == "function" then
            local oldDouble = tip.AddDoubleLine
            tip.AddDoubleLine = function(self, left, right, lr, lg, lb, rr, rg, rb, size)
                return oldDouble(self, enabled and Translate(left) or left, enabled and Translate(right) or right, lr, lg, lb, rr, rg, rb, size)
            end
        end
        spellTipHooked = true
    end
    -- Also intercept existing GameTooltip writers regardless of owner name:
    -- some cards have anonymous buttons or tooltips whose owner changes.
    if not gameTipHooked and GameTooltip and type(GameTooltip.AddLine) == "function" then
        local oldLine = GameTooltip.AddLine
        GameTooltip.AddLine = function(self, content, r, g, b, wrap)
            if enabled and self == GameTooltip then
                local changed = Translate(content)
                if changed ~= content then content = changed; wrap = 1 end
            end
            return oldLine(self, content, r, g, b, wrap)
        end
        if type(GameTooltip.AddDoubleLine) == "function" then
            local oldDouble = GameTooltip.AddDoubleLine
            GameTooltip.AddDoubleLine = function(self, left, right, lr, lg, lb, rr, rg, rb)
                if enabled and self == GameTooltip then left, right = Translate(left), Translate(right) end
                return oldDouble(self, left, right, lr, lg, lb, rr, rg, rb)
            end
        end
        if type(GameTooltip.SetText) == "function" then
            local oldText = GameTooltip.SetText
            GameTooltip.SetText = function(self, content, r, g, b, a, wrap)
                if enabled and self == GameTooltip then content = Translate(content) end
                return oldText(self, content, r, g, b, a, wrap)
            end
        end
        gameTipHooked = true
    end
end

-- Some Hordes game tooltips are anonymous, not descendants of VanillaBonk*.
-- Only scan unnamed tooltip-strata frames, not arbitrary addon windows.
local function ScanAnonymousTooltips()
    if not UIParent or not UIParent.GetChildren then return end
    local roots = {UIParent:GetChildren()}
    checked = 0
    for _, current in ipairs(roots) do
        if current and current.IsShown and current:IsShown() and current.GetFrameStrata
           and current:GetFrameStrata() == "TOOLTIP" then
            ScanFrame(current, 0)
        end
    end
    if GameTooltip and GameTooltip.IsShown and GameTooltip:IsShown() then
        ScanFrame(GameTooltip, 0)
    end
end

