local FONT_SC = "Interface\\AddOns\\HordesOfAzeroth\\Fonts\\NotoSansSC-Regular.otf"
local compactFontCache = setmetatable({}, {__mode = "k"})
local function SelectedRUFont()
    if HordesRU_Options and HordesRU_Options.font == "sc" then return FONT_SC end
    return FONT_KR
end
local function SyncHordesFont()
    if type(VanillaBonkUI) == "table" then
        VanillaBonkUI.FONT = SelectedRUFont()
    end
