-- WoW 1.12 runs Lua 5.0; string.match was added in 5.1.
local function Match(value, pattern)
    local _,_,a,b,c = string.find(value, pattern)
    return a,b,c
end
local total = 0
for _ in pairs(Missing) do total = total + 1 end

local function AddMissing(text)
    if type(text) ~= "string" then return end
    if string.len(text) < 4 or string.len(text) > 2400 then return end
    if not string.find(text, "[A-Za-z]") then return end
    if string.find(text, "^%d+[%s/%.%%%d+-]*$") then return end
    if not Missing[text] and total < 2000 then
        Missing[text] = 1
        total = total + 1
    end
end

local function CheckEnglishName(text)
    local l = VanillaBonkLocale
    if l and l.tables and l.tables.ruRU then
        local value = l.tables.ruRU[text]
        if type(value) == "string" and value ~= text then return value end
    end
    return nil
end

local function Numbered(text)
    -- Localized quantity forms for text assembled by the server.
    local number = Match(text, "^(%d+) tickets spent$")
    if number then return "Потрачено билетов: " .. number end
    number = Match(text, "^(%d+) Darkmoon Tickets$")
    if number then return number .. " билетов Новолуния" end
    number = Match(text, "^(%d+) Darkmoon Ticket$")
    if number then return number .. " билет Новолуния" end
    number = Match(text, "^(%d+) tickets$")
    if number then return number .. " билетов" end
    number = Match(text, "^(%d+) copies$")
    if number then return "Копий: " .. number end
    number = Match(text, "^(%d+) copy$")
    if number then return "Копия: " .. number end
    number = Match(text, "^(%d+)%% chance$")
    if number then return "Шанс: " .. number .. "%" end
    number = Match(text, "^(%d+) sec recharge$")
    if number then return "Перезарядка: " .. number .. " сек." end
    number = Match(text, "^(%d+) charges$")
    if number then return "Зарядов: " .. number end
    local current, maximum = Match(text, "^(%d+)/(%d+) charges$")
    if current then return "Заряды: " .. current .. "/" .. maximum end
    current, maximum = Match(text, "^(%d+)/(%d+) copies$")
    if current then return "Копии: " .. current .. "/" .. maximum end
    number = Match(text, "^[Nn]ormal (%d+)$")
    if number then return "Обычный " .. number end
    number = Match(text, "^[Hh]eroic (%d+)$")
    if number then return "Героический " .. number end
    number = Match(text, "^[Mm]ythic (%d+)$")
    if number then return "Мифический " .. number end
    number = Match(text, "^(%d+) tickets spent$")
    if number then return "Потрачено билетов: " .. number end
    local count, what = Match(text, "^Kill ([%d,]+) (.-)%.$")
    if not count then count,what = Match(text, "^Kill ([%d,]+) (.+)$") end
    if count then
        if what == "mini-bosses" then return "Убейте " .. count .. " мини-боссов." end
        if what == "stage bosses" then return "Убейте " .. count .. " боссов этапов." end
        if what == "elites" then return "Убейте " .. count .. " элитных врагов." end
        if what == "enemies" then return "Убейте " .. count .. " врагов." end
        if what == "enemies with physical attacks" then return "Убейте " .. count .. " врагов физическими атаками." end
        local spell = Match(what, "^enemies with (.+)$")
        if spell then
            local name = CheckEnglishName(spell) or Exact[spell] or spell
            return "Убейте " .. count .. " врагов с помощью «" .. name .. "»."
        end
    end
    count,what = Match(text, "^Defeat ([%d,]+) (.+)%.$")
    if not count then count,what = Match(text, "^Defeat ([%d,]+) (.+)$") end
    if count then
        if what == "stage bosses" then return "Победите " .. count .. " боссов этапов." end
        if what == "mini-bosses" then return "Победите " .. count .. " мини-боссов." end
        if what == "elites" then return "Победите " .. count .. " элитных врагов." end
    end
    local a,b=Match(text, "^(%d+) tickets spent, (%d+) more needed$")
    if a then return "Потрачено билетов: "..a..", нужно ещё "..b end
    return nil
end

local function ReplaceTemplates(text)
    -- Only structured English templates. Never blindly translate isolated words.
    local match = Match(text, "^Unlocked at (%d+) tickets spent$")
    if match then return "Доступно после траты "..match.." билетов" end
    match = Match(text, "^[Ee]ach stage boss arrives (%d+) sec earlier%. %+(%d+)%% gold%.$")
    if match then
        local sec, percent = Match(text, "^[Ee]ach stage boss arrives (%d+) sec earlier%. %+(%d+)%% gold%.$")
        return "Каждый босс этапа появляется на "..sec.." сек. раньше. +"..percent.."% золота."
    end
    match = Match(text, "^Stage boss arrives (%d+) sec earlier%. %+(%d+)%% gold%.$")
    if match then
        local seconds,percent=Match(text, "^Stage boss arrives (%d+) sec earlier%. %+(%d+)%% gold%.$")
        return "Босс этапа появляется на "..seconds.." сек. раньше. +"..percent.."% золота."
    end
    local cost = Match(text, "^Cost: ([%d,]+) Darkmoon Tickets$")
    if cost then return "Стоимость: "..cost.." билетов Новолуния" end
    local value = Match(text, "^%+(%d+)%% gold$")
    if value then return "+"..value.."% золота" end
    value = Match(text, "^%+(%d+)%% gold and Darkmoon Tickets$")
    if value then return "+"..value.."% золота и билетов Новолуния" end
    local stage = Match(text, "^Stage (%d+) is a random Normal zone%.$")
    if stage then return "Этап "..stage.." — случайная обычная зона." end
    local left, right = Match(text, "^(%d+) / (%d+) done$")
    if left then return "Выполнено: "..left.."/"..right end
    return nil
end


-- Translate server-supplied numeric tooltips and mixed-language equipment rows.
local function TranslateFragments(text)
    local work = text
    -- Exact card text often appears as part of a line with an added suffix.
    if not string.find(work, "[A-Za-z]") then return nil end
    if string.find(work, "%(Epic, ", 1, false) then
        work = string.gsub(work, "%(Epic, все классы%)", "(эпическая, все классы)")
        work = string.gsub(work, "%(Epic, all classes%)", "(эпическая, все классы)")
    end
    work = string.gsub(work, "^%s*Classes:%s*", "Классы: ")
    if string.find(work, "Классы:", 1, true) then
        for english, russian in pairs({Hunter="Охотник", Rogue="Разбойник", Shaman="Шаман", Druid="Друид", Warrior="Воин", Paladin="Паладин", Mage="Маг", Priest="Жрец", Warlock="Чернокнижник"}) do
            work = string.gsub(work, english, russian)
        end
    end
    work = string.gsub(work, "^Item Level:%s*(%d+)$", "Уровень предмета: %1")
    work = string.gsub(work, "^%+(%d+%.?%d*)[kK] Armor%.?$", "+%1 тыс. к броне")
    work = string.gsub(work, "^%+(%d+%.?%d*) Armor%.?$", "+%1 к броне")
    work = string.gsub(work, "^%+(%d+%.?%d*)%% Max health%.?$", "+%1%% к максимальному здоровью")
