local function StyleCompact(fs)
    if not fs or type(fs.GetFont) ~= "function" or type(fs.SetFont) ~= "function" then return end
    local path = SelectedRUFont()
    -- Hordes rebuilds some tooltip text every frame: checking actual font is
    -- important, a stale cache alone would skip the change.
    local ok, old, size = pcall(fs.GetFont, fs)
    if not ok or not size or size <= 0 then return end
    if old == path then compactFontCache[fs] = path; return end
    local success, applied = pcall(fs.SetFont, fs, path, size, "")
    if success and applied then compactFontCache[fs] = path end
end
SyncHordesFont()

local function TranslateFontString(fs)
    if not fs or not fs.IsShown or not fs:IsShown() or not fs.GetText or not fs.SetText then return end
    StyleCompact(fs)
    local original = fs:GetText()
    if type(original) ~= "string" or original == "" then return end
    local localized = Translate(original)
    if localized ~= original then
        pcall(fs.SetText, fs, localized)
    else
        AddMissing(original)
    end
end

local checked = 0
local function ScanFrame(frame, depth)
    if depth > 15 or checked >= 3600 or not frame or not frame.IsShown or not frame:IsShown() then return end
    checked = checked + 1
    if frame.GetRegions then
        local regions = { frame:GetRegions() }
        for _, region in ipairs(regions) do
            if region and region.GetObjectType and region:GetObjectType() == "FontString" then
                TranslateFontString(region)
            end
        end
    end
    if frame.GetChildren then
        local children = { frame:GetChildren() }
        for _, child in ipairs(children) do
            ScanFrame(child, depth + 1)
            if checked >= 3600 then break end
        end
    end
end

local function IsHordesWidget(widget)
    local current = widget
    for n = 1, 16 do
        if not current or not current.GetName then return false end
        local name = current:GetName()
        if type(name) == "string" and string.find(name, "VanillaBonk", 1, true) then return true end
        if not current.GetParent then break end
        current = current:GetParent()
    end
    return false
end

local function IsHordesTooltip(tip)
    if not tip or not tip.GetOwner then return false end
    if tip.GetName then
        local name = tip:GetName()
        if type(name) == "string" and string.find(name, "VanillaBonk", 1, true) then return true end
    end
    local owner = tip:GetOwner()
    if IsHordesWidget(owner) then return true end
    if owner == GameTooltip and GameTooltip.GetOwner and IsHordesWidget(GameTooltip:GetOwner()) then return true end
    return false
end

local function ScanUI()
    if not UIParent or not UIParent.GetChildren then return end
    checked = 0
    local top = {UIParent:GetChildren()}
    for _,child in ipairs(top) do
        if child.GetName then
            local name = child:GetName()
            if type(name) == "string" and string.find(name, "VanillaBonk", 1, true) then
                ScanFrame(child, 0)
            end
        end
    end
    local tips = {GameTooltip, ShoppingTooltip1, ShoppingTooltip2}
    for i = 1, 3 do
        local tip = tips[i]
        if tip and tip.IsShown and tip:IsShown() and IsHordesTooltip(tip) then
            ScanFrame(tip, 0)
        end
    end
end

local localeInstalled = false
local tipInstalled = false
local function Install()
    SyncHordesFont()
    local loc = VanillaBonkLocale
    if not localeInstalled and type(loc) == "table" and type(loc.Text) == "function" then
        local previous = loc.Text
        loc.Text = function(lang, english)
            local translated = previous(lang, english)
            if lang == "ruRU" and type(english) == "string" and translated == english then
                return Exact[english] or translated
            end
            return translated
        end
        localeInstalled = true
    end
    if not tipInstalled and GameTooltip and type(GameTooltip.AddLine) == "function" then
        local previous = GameTooltip.AddLine
        GameTooltip.AddLine = function(self, content, r, g, b, wrap)
            if IsHordesTooltip(self) then
                local translated = Translate(content)
                if translated ~= content then content = translated; wrap = 1 end
            end
            return previous(self, content, r, g, b, wrap)
        end
        if type(GameTooltip.AddDoubleLine) == "function" then
            local originalDouble = GameTooltip.AddDoubleLine
            GameTooltip.AddDoubleLine = function(self, left, right, lr, lg, lb, rr, rg, rb)
                if enabled and IsHordesTooltip(self) then
                    left, right = Translate(left), Translate(right)
                end
                return originalDouble(self, left, right, lr, lg, lb, rr, rg, rb)
            end
        end
        if type(GameTooltip.SetText) == "function" then
            local originalText = GameTooltip.SetText
            GameTooltip.SetText = function(self, content, r, g, b, a, wrap)
                if enabled and IsHordesTooltip(self) then content = Translate(content) end
                return originalText(self, content, r, g, b, a, wrap)
            end
        end
        tipInstalled = true
    end
end

