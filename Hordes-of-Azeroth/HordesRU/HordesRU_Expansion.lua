        {"^%+(%d+%.?%d*)%% critical strike chance%.?$", "+%1%% к шансу критического удара."},
        {"^%+(%d+%.?%d*)%% critical strike damage%.?$", "+%1%% к критическому урону."},
        {"^%+(%d+%.?%d*)%% Haste%.?$", "+%1%% к скорости действий."},
        {"^%+(%d+%.?%d*)%% Area%.?$", "+%1%% к области действия."},
        {"^%+(%d+%.?%d*)%% Power%.?$", "+%1%% к мощи."},
    }
    for i = 1, table.getn(patterns) do
        result = string.gsub(result, patterns[i][1], patterns[i][2])
        if result ~= before then return result end
    end
