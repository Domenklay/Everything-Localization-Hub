local catalogue = HordesRU_Catalog
local registeredTable = nil
local function RegisterDictionary()
  local locale = VanillaBonkLocale
  if type(locale) ~= "table" or type(locale.tables) ~= "table" then return end
  local strings = locale.tables["ruRU"]
  if type(strings) ~= "table" or strings == registeredTable then return end
  for english, russian in pairs(catalogue) do strings[english] = russian end
  registeredTable = strings
end

local function TranslateField(value)
  if type(value) ~= "string" then return value end
  return catalogue[value] or value
end

local function TranslateTalent(node)
  if type(node) ~= "table" then return end
  if type(node.name) == "string" then
    local english = node._HordesRU_EnglishName or node.name
    local russian = TranslateField(english)
    if russian ~= english then node._HordesRU_EnglishName = english; node.name = russian end
  end
  if type(node.description) == "string" then
    local english = node._HordesRU_EnglishDescription or node.description
    local russian = TranslateField(english)
    if russian ~= english then node._HordesRU_EnglishDescription = english; node.description = russian end
  end
end

local talentsHooked = false
local function HookTalentPanels()
  if talentsHooked then return end
  local talents = VanillaBonkTalents
  if type(talents) ~= "table" or type(talents.Show) ~= "function" then return end
  talentsHooked = true
  local previousShow = talents.Show
  talents.Show = function(shop, data, top)
    if type(data) == "table" then
      if type(data.nodes) == "table" then
        for _, node in pairs(data.nodes) do TranslateTalent(node) end
      end
      if type(data.trees) == "table" then
        for _, tree in ipairs(data.trees) do
          if type(tree.name) == "string" then tree.name = TranslateField(tree.name) end
        end
      end
    end
    return previousShow(shop, data, top)
  end
end

local tooltipHooked = false
local function HookTalentTooltips()
  if tooltipHooked or not GameTooltip or type(GameTooltip.AddLine) ~= "function" then return end
  tooltipHooked = true
  local original = GameTooltip.AddLine
  GameTooltip.AddLine = function(self, text, red, green, blue, wrap)
    if self == GameTooltip and type(text) == "string" then
      local owner = self.GetOwner and self:GetOwner()
      if owner and (owner.node or owner.pair) then
        local translated = TranslateField(text)
        if translated ~= text then text = translated; wrap = 1 end
      end
    end
    return original(self, text, red, green, blue, wrap)
  end
end

local active = CreateFrame("Frame")
local lastRun = 0
active:SetScript("OnUpdate", function()
  local now = GetTime()
  if now < lastRun then return end
  lastRun = now + 2
  RegisterDictionary()
  HookTalentPanels()
  HookTalentTooltips()
end)
RegisterDictionary()
HookTalentPanels()
HookTalentTooltips()
